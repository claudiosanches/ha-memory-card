-- Platforms added without an IGDB id are linked by name.
UPDATE platforms
SET igdb_platform_id = (
    SELECT i.igdb_platform_id FROM igdb_platforms i WHERE i.name = platforms.name COLLATE NOCASE
)
WHERE igdb_platform_id IS NULL
  AND EXISTS (
      SELECT 1 FROM igdb_platforms i
      WHERE i.name = platforms.name COLLATE NOCASE
        AND i.igdb_platform_id NOT IN (SELECT igdb_platform_id FROM platforms WHERE igdb_platform_id IS NOT NULL)
  );

UPDATE platforms
SET generation = COALESCE(generation, (SELECT i.generation FROM igdb_platforms i WHERE i.igdb_platform_id = platforms.igdb_platform_id)),
    family     = COALESCE(family, (SELECT i.family FROM igdb_platforms i WHERE i.igdb_platform_id = platforms.igdb_platform_id)),
    category   = (SELECT i.category FROM igdb_platforms i WHERE i.igdb_platform_id = platforms.igdb_platform_id)
WHERE igdb_platform_id IS NOT NULL;

-- Name, slug or IGDB id conflicts mean the platform is already there.
INSERT OR IGNORE INTO platforms
    (igdb_platform_id, name, abbreviation, slug, generation, family, category, active, sort_order)
SELECT igdb_platform_id, name, abbreviation, slug, generation, family, category, 0, 1000 + position
FROM igdb_platforms
ORDER BY position;

